"""
Python 变量基础知识
"""

# -----------------------------------------
# 1. 什么是变量？
# -----------------------------------------
# 变量就像是一个“容器”或“标签”，用来存储数据。
# 在 Python 中，不需要提前声明变量的类型，直接赋值即可创建变量。

# -----------------------------------------
# 2. 变量的赋值
# -----------------------------------------
# 使用等号（=）将右边的值赋给左边的变量。
name = "张三"      # 字符串类型 (String)
age = 25           # 整数类型 (Integer)
height = 1.75      # 浮点数类型 (Float)
is_student = True  # 布尔类型 (Boolean)

print("--- 2. 变量的赋值 ---")
print("姓名:", name)
print("年龄:", age)

# -----------------------------------------
# 3. 变量命名规则 (重要)
# -----------------------------------------
# - 只能包含字母、数字和下划线（A-Z, a-z, 0-9, _）
# - 不能以数字开头（例如 1name 是错误的，name1 是正确的）
# - 严格区分大小写（Age 和 age 是两个不同的变量）
# - 不能使用 Python 的关键字（如 if, for, while, class 等）
# - 推荐使用“下划线命名法”（snake_case），例如 user_name, max_speed

# -----------------------------------------
# 4. 动态类型特性
# -----------------------------------------
# Python 是动态类型语言，同一个变量可以先后存储不同类型的数据。
print("\n--- 4. 动态类型特性 ---")
my_var = 100       # 此时是整数
print("my_var 的值:", my_var, "，类型:", type(my_var))

my_var = "Hello"   # 现在变成了字符串
print("my_var 的值:", my_var, "，类型:", type(my_var))

# -----------------------------------------
# 5. 多变量赋值
# -----------------------------------------
print("\n--- 5. 多变量赋值 ---")
# 方式一：同时为多个变量赋不同的值
a, b, c = 1, 2, 3
print(f"a={a}, b={b}, c={c}")

# 方式二：为多个变量赋相同的值
x = y = z = 0
print(f"x={x}, y={y}, z={z}")

# -----------------------------------------
# 6. 原代码示例分析 (用户输入与变量交互)
# -----------------------------------------
print("\n--- 6. 用户输入与变量交互示例 ---")
# input() 函数接收用户的输入，并将其作为字符串返回，赋值给变量 n
n = input("请输入一个数字：")

# 注意：input() 接收到的所有内容默认都是字符串类型 (str)
# 如果需要进行数学计算，需要使用 int() 或 float() 将其转换为数字类型
# 取消下面的注释可以把字符串转为整数
# n = int(n) 

print("你输入的内容是:", n)
print("此时变量 n 的类型是:", type(n))
